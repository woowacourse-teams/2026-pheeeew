// 구간 4 열기구 축제 하늘 (화면 7장, 내 높이 0~126). 높이는 "내 시작 바닥이 0" 기준이다. 시작 바닥은 아래 구간의 맨 위 쉼터(칸 1~14).
// 주제 장치는 바람(wind). 구역 안의 공중에서만 옆으로 민다. 순풍은 넘치기 쉽고(상한이 생긴다), 맞바람은 더 세게 뛰어야 닿는다.
// 큰 구조:
//   왼쪽 낙하 통로(칸 1~6, 높이 38~124): 화면 4 병목과 관문에서 넘치면 받이 턱(높이 38)까지 떨어진다.
//   갑판(높이 56, 칸 8~24): 화면 4·5의 실수를 받는다. 오른쪽 구멍(칸 25~30) 밑은 받이 발판(높이 52)이 막는다.
//   화면 3의 실수는 축제 마당(높이 20)까지 떨어진다.
//   경사가 벽이나 덩어리 바로 옆에서 끝나면 미끄러지다 끼어 버린다(물리 한계). 경사 끝에는 늘 2칸 넘게 비워 둔다.
// 설계 메모: docs/research/zone4_design.md
export const top = 126;
export default function build({ rock, up, down, nod, wind }) {
  // ── 화면 1 (0~18) 깃발 마당: 바람을 안전하게 배운다. 왼쪽 절반은 바람이 없고 오른쪽 절반만 왼쪽으로 분다. 낙하 6칸 이하 ──
  rock(7, 8, 1, 3); // 바구니 1(높이 3): 바람 없는 곳의 첫 디딤. 위 갑판 밑이라 너무 세게 뛰면 머리를 박는다
  rock(16, 30, 5, 6); // 아래 갑판(6). 여기부터 바람 구역(왼쪽으로 분다)
  rock(27, 28, 9, 11); // 바구니 2(높이 11): 왼쪽에서는 맞바람을 뚫고 세게, 오른쪽 끝에서는 제자리 점프로 바람에 실려 오른다
  rock(1, 14, 10, 11); // 위 갑판(11): 바구니 2에서 순풍을 타고 12칸을 건너온다. 아래 갑판 왼쪽 끝의 제자리 점프도 여기로 실려 온다
  rock(8, 8, 12, 14); // 1칸 바구니(14): 벽 쪽 바구니로 가는 쉬운 디딤(안 밟아도 된다)
  rock(1, 2, 14, 16); // 벽 쪽 바구니(16): 여기서 마당 왼쪽 끝으로
  wind(15, 30, 6, 18, -250);

  // ── 화면 2 (18~36) 구름 징검다리: 맞바람 속 짧은 건너뛰기, 바람 경계를 걸친 점프. 실수하면 마당(20) ──
  rock(5, 30, 18, 20); // 축제 마당(20). 화면 3에서 떨어지는 곳이기도 하다
  rock(16, 17, 21, 23); // 바구니(23)
  nod(14, 14, 27); // 구름 1칸(27): 맞바람 속 짧은 점프. 넘치면 마당 (이 화면에서 가장 좁다)
  rock(6, 7, 28, 30); // 바람 밖 바구니(30): 앞 절반만 맞바람을 맞고 건너온다
  nod(11, 12, 34); // 구름 2칸(34): 바람 없는 곳에서 뛰어 순풍 속에 내린다(뒤 절반만 밀린다)
  wind(9, 30, 20, 36, 300);
  rock(1, 7, 36, 38); // 받이 턱(38): 왼쪽 낙하 통로의 바닥. 화면 3의 출발점

  // ── 화면 3 (36~54) 풍선 능선: 순풍에 넘치기 쉬운 좁은 착지. 넘치거나 모자라면 마당(20)까지 ──
  up(10, 39, 2, { to: 39 }); rock(12, 13, 39, 41); down(14, 40, 2, { to: 39 }); // 풍선 꼭대기(41): 양옆은 미끄러운 천
  nod(19, 19, 45); // 구름 1칸(45): 병목. 순풍 속 4칸 위 1칸짜리 착지
  rock(24, 25, 47, 49); // 바구니(49): 풍선 꼭대기에서는 8칸이라 바로 못 온다: 다음 점프가 모자라면 여기서 받는다
  rock(26, 30, 50, 52); // 받이 발판(52): 갑판 구멍 밑. 위에서 구멍으로 떨어져도 여기서 멈춘다: 갑판 구멍 밑. 위에서 구멍으로 떨어져도 여기서 멈춘다
  wind(9, 30, 36, 54, 300);
  rock(8, 24, 54, 56); // 갑판(56)

  // ── 화면 4 (54~72) 맞바람 바구니: 테가 기울어진 바구니 안에 쏙 내려야 한다. 모자라면 제자리, 넘치면 왼쪽 통로로 29칸 ──
  rock(21, 21, 56, 58); // 갑판 위 상자(58): 여기서만 깃대 발판에 닿는다
  rock(15, 15, 61, 63); // 깃대 발판(63)
  rock(7, 11, 65, 67); up(7, 67, 1); down(11, 67, 1); // 큰 바구니(안쪽 바닥 67, 칸 8~10): 병목. 테에 내리면 바깥으로 미끄러진다
  rock(15, 17, 70, 71); // 깃발 줄 다리(71)
  wind(8, 23, 64, 72, 100);

  // ── 화면 5 (72~90) 바람 기둥: 오른쪽 기둥(칸 19~30)만 센 순풍. 바람과 풍선 경사가 겹친다. 넘치면 갑판(56)까지 ──
  up(20, 73, 2, { to: 73 }); rock(22, 23, 73, 75); down(24, 74, 2, { to: 73 }); // 풍선 꼭대기(75)
  nod(17, 17, 78); // 바람 밖 구름(78): 맞바람을 뚫고 기둥 밖으로 나온다
  up(23, 82, 1); rock(24, 24, 81, 83); down(25, 82, 1); // 작은 풍선 꼭대기(83): 병목. 구름에서 뛰자마자 순풍에 실린다
  rock(29, 30, 84, 86); // 벽 쪽 바구니(86)
  wind(19, 30, 71, 88, 400);

  // ── 화면 6 (90~104) 큰 풍선 꼭대기: 숨 고르기. 바람 없음, 창 17 이상, 떨어져도 바닥(90) ──
  rock(7, 25, 88, 90); // 넓은 바닥(90)
  rock(7, 7, 90, 106); // 깃대: 왼쪽 낙하 통로로 걸어 나가지 못하게 막는다
  rock(25, 25, 90, 91); // 오른쪽 턱: 걸어서는 떨어지지 않는다
  rock(19, 20, 90, 93); // 상자(93)
  nod(13, 14, 96); // 구름(96)
  up(18, 99, 1); rock(19, 20, 98, 100); down(21, 99, 1); // 풍선 꼭대기(100)
  rock(13, 14, 102, 104); // 바구니(104)

  // ── 화면 7 (104~126) 관문 폭풍: 오른쪽(바람 없음)으로 올라가, 마지막에 왼쪽 통로 쪽으로 부는 센 순풍 속 1칸 발판에 내린다 ──
  //    그 점프가 이 구간에서 가장 좁다(창 7). 모자라면 넓은 바닥(90)으로 28칸, 넘치면 왼쪽 통로로 80칸. 끝까지 누르면 언제나 넘친다
  rock(19, 20, 104, 106); // 바구니(106)
  rock(24, 24, 108, 110); // 1칸 바구니(110)
  rock(27, 30, 104, 105); // 오른쪽 받이(105): 1칸 바구니에서 넘쳐도 여기서 멈춘다
  rock(17, 17, 111, 113); // 발사대(113): 갑판 밑 1칸. 여기서 왼쪽으로 뛰면 칸 18부터 순풍에 실린다
  rock(11, 11, 117, 118); // 1칸 발판(118): 관문 병목. 쉼터 밑을 지나 갑판 왼쪽 끝으로 올라간다
  rock(16, 30, 121, 122); // 꼭대기 갑판(122)
  rock(17, 17, 122, 123); // 갑판 턱: 쉼터에서 떨어진 사람이 왼쪽으로 걸어 나가지 않게
  wind(1, 18, 108, 124, -300);

  // ── 구간 5 쉼터 ──
  rock(1, 14, top - 2, top);
}

