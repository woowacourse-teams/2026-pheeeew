// 큰 구조: 오른쪽에 큰 굴뚝 통로(칸 25~27, 높이 156~225)가 있고 바닥은 벽난로(높이 149)다.
//   과자집 1~3층의 마지막 점프와 관문에서 굴뚝 쪽으로 실패하면 벽난로까지 떨어지고,
//   벽난로에서 문(높이 153)으로 뛰어 1층으로 돌아온다.
