  // ── 화면 7 (117~135) 눈 쌓인 마당: 꾸벅 눈더미 소개. 어디서 떨어져도 시작 바닥(6칸 이하) ──
  rock(1, 2, 125, 137); // 왼쪽 벽
  nod(8, 12, 123); // 눈더미 1: 왼쪽 끝에 내려 사탕 기둥 밑을 걸어 오른쪽 끝에서 뛴다(1.4~1.8초). 머뭇거리면 꺼진다
  rock(9, 10, 125, 133); // 사탕 기둥: 밑면이 처마. 눈더미에서 여기에 튕겨 선물 탑으로 갈 수도 있다
  rock(15, 16, 120, 127); // 선물 탑(127). 아래로 길게 내려와 오른쪽 바닥에서 눈더미로 뛰는 길을 막는다
  rock(25, 30, 125, 149); // 오른쪽 탑. 꼭대기(149)가 벽난로 바닥
  rock(21, 24, 125, 129); // 탑 앞 턱. 굴뚝을 넘기면 홈(129)에 빠지고, 탑 벽에 튕겨 나온다
  rock(22, 22, 129, 131); // 작은 굴뚝(폭 1칸)
  rock(15, 18, 133, 135); // 매달린 선물 상자. 선물 탑의 천장이기도 하다

  // ── 화면 8 (135~153) 고드름 처마: 눈더미를 걸어 지나 벽 틈(2칸)으로. 실패하면 마당까지 ──
  nod(9, 13, 139); // 눈더미 2: 오른쪽 끝에 내려 고드름 밑을 걸어 왼쪽 끝에서 뛴다
  rock(11, 12, 141, 147); // 고드름 기둥. 밑면이 처마, 윗면(147)이 다음 발판
  rock(1, 3, 137, 143); // 벽 틈 바닥(143)
  rock(1, 3, 145, 161); // 벽 틈 천장(틈 높이 2칸). 나올 때는 가장자리에서 뛴다
  rock(4, 9, 150, 151); // 1층 왼쪽 마루(151). 틈에서 나오는 점프의 천장이고, 1층에서 놓쳤을 때 받이

  // ── 화면 9 (153~171) 과자집 1층: 눈더미 → 벽장 틈(3칸) → 들보 → 창턱 → 굴뚝 벽 튕김(병목) ──
  rock(15, 24, 151, 153); // 1층 바닥. 오른쪽 끝이 벽난로로 통하는 문(높이 153~156)
  rock(22, 24, 149, 151); // 벽난로 왼쪽을 막아 닫힌 받이로 만든다
  rock(23, 24, 156, 165); // 집 오른쪽 벽. 165~168 이 창문 1
  rock(28, 30, 156, 225); // 굴뚝 건너편 벽
  nod(12, 16, 157); // 눈더미 3
  rock(14, 15, 159, 161); // 들보. 밑면이 처마, 윗면(161)에서 창턱으로 뛴다
  rock(4, 6, 159, 161); // 벽장 바닥(161)
  rock(1, 6, 164, 172); // 벽장 천장(틈 높이 3칸)
  rock(7, 9, 170, 172); // 받이 선반: 2층 눈더미에서 놓치면 여기(172)
  rock(19, 24, 168, 170); // 2층 바닥. 오른쪽 끝(170~172)이 창문 2(높이 2칸): 창턱 1에서 굴뚝 벽에 튕겨 들어온다

  // ── 화면 10 (171~189) 과자집 2층: 눈더미 2연속 → 들보 → 창턱 → 굴뚝 벽 튕김(병목, 벽난로까지 34칸) ──
  rock(23, 24, 172, 183); // 집 오른쪽 벽. 183~186 이 창문 3
  nod(12, 16, 174); // 눈더미 4: 처마 밑을 걸어 왼쪽 끝에서 뛴다
  rock(14, 15, 176, 179); // 들보
  nod(3, 5, 177); // 눈더미 5
  rock(9, 24, 186, 188); // 3층 바닥(넓은 받이). 오른쪽 끝(188~190)이 창문 4(높이 2칸)

  // ── 화면 11 (189~207) 과자집 3층: 벽 틈(2칸) → 가장자리 발사 → 눈더미(처마) → 천장 아래 창턱 → 굴뚝 벽 튕김(병목, 52칸) ──
  rock(23, 24, 190, 201); // 집 오른쪽 벽. 201~203 이 창문 5(높이 2칸)
  rock(1, 4, 190, 192); // 벽 틈 바닥(192)
  rock(1, 4, 194, 206); // 벽 틈 천장(틈 높이 2칸). 다락 바닥까지 이어져 올라설 수 없다
  rock(9, 11, 193, 195); // 매달린 상자
  nod(13, 17, 198); // 눈더미 6: 왼쪽 끝에 내려 처마 밑을 걸어 오른쪽 끝에서 뛴다
  rock(14, 15, 200, 204); // 다락 바닥에서 내려온 기둥(처마)
  rock(23, 24, 203, 206); // 창문 5 위 벽
  rock(9, 24, 204, 206); // 다락 바닥. 오른쪽 끝(206~208)이 창문 6(높이 2칸). 창턱 점프의 천장이기도 하다

  // ── 화면 12 (207~225) 다락: 숨 고르기. 서로 다른 점프 5번, 떨어져도 다락 바닥 ──
  rock(23, 24, 208, 223); // 집 오른쪽 벽
  rock(1, 5, 206, 210); // 다락 선반(210)
  nod(9, 13, 214); // 눈더미 7
  rock(17, 18, 213, 215); // 매달린 상자(짧게 건너뛰기, 넘치면 바닥)
  rock(8, 9, 218, 220); // 높은 상자(멀리 뛰기)

  // ── 화면 13 (225~243) 관문 굴뚝 능선: 능선 오른쪽은 굴뚝으로 쏟아지는 지붕. 놓치면 벽난로(149)까지 ──
  rock(12, 17, 223, 225); // 지붕 왼쪽 평지
  rock(18, 18, 223, 231); // 능선(폭 1칸). 넘치면 오른쪽 경사를 타고 굴뚝으로 떨어진다
  down(19, 230, 6, { to: 223 }); // 굴뚝으로 쏟아지는 지붕
  rock(28, 30, 225, 231);
  up(28, 231, 1); // 건너편도 굴뚝 쪽으로 미끄럽다
  rock(29, 30, 231, 235); // 굴뚝 갓(235). 능선에서 뛰어 3칸 틈으로 들어간다(관문 병목)
  rock(29, 30, 238, 240); // 굴뚝 갓 지붕
  rock(16, 22, 240, 241); // 쉼터 옆 받이(241): 쉼터에서 오른쪽으로 걷거나 뛰어도 1~2칸 아래 여기에 선다
  rock(21, 22, 241, 242); // 받이 오른쪽 끝 단(242): 굴뚝 갓에서 끝까지 눌러 여기로 뛰고, 톡 뛰어 쉼터로 간다

