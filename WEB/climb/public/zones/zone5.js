// 구간 5 로켓 발사대와 우주 (내 높이 0~130, 화면 7장 남짓). 게임의 마지막 구간이고 이 위는 달뿐이다.
// 높이는 "내 시작 바닥이 0"이라고 보고 쓴다. 시작 바닥은 아래 구간의 맨 위 쉼터(칸 1~14)다.
// 큰 구조:
//   로켓 동체(칸 14~17, 높이 20~74)가 발사대를 왼쪽·오른쪽으로 가른다. 노즐 밑(높이 18~20)과 승무원 통로(57~59)로만 건넌다.
//   오른쪽 끝 통로(칸 28~30, 높이 35~100)는 낙하 통로다. 바닥은 받이(높이 35)이고 턱(37)으로 닫혀 있다.
//   화면 3 병목에서 넘치면 받이까지, 최종 관문의 앞 세 점프에서 실패하면 큰 태양 전지판을 타고 이 통로로 받이까지 떨어진다(약 80칸).
//   로켓 머리(경사)에서 미끄러지면 승무원 통로 앞(57)이나 받이 선반(68)에 떨어진다.
// 장치: hot = 달궈진 판(1.8초 서면 튕겨 낸다), boost = 분사 판(점프 1.4배). 분사 판은 발판 전체를 덮어야 한다(일부만 덮으면 옆에서 보통 점프로 뛴다).
// 주의: 목표 바로 앞·위에 천장을 두면 "머리 박고 뚝 떨어져 착지"가 되어 세게 뛰어도 성공한다. 상한은 "넘치면 지나쳐 떨어진다"로 만든다.
// 설계 메모: docs/research/zone5_design.md
export const top = 130;
export default function build({ rock, up, down, nod, hot, boost, wind }) {
  // ── 화면 1 (0~18) 엔진 시험장: 달궈진 판 소개. 튕겨도 3칸 아래 바닥이다 ──
  hot(6, 8, 3); // 달궈진 판 1: 내려서 오른쪽 끝까지 걸어가 뛴다(약 1.1초)
  rock(5, 9, 8, 13); // 시험대 지붕. 밑면은 판 1의 천장, 윗면(13)은 마지막 발판(위 갑판의 구멍 바로 밑)
  rock(16, 30, 5, 6); // 오른쪽 갑판(6). 높이 0~5는 아래 구간이 쉼터로 올라오는 길이라 비워 둔다
  hot(22, 23, 9); // 달궈진 판 2(왼쪽 2칸만 뜨겁다): 판 위에서 약 1.0초. 반응 0.25초를 넣어도 된다
  rock(24, 25, 8, 9); // 판 2의 오른쪽 절반은 보통 바닥. 여기 내려 배관 밑을 걸어간다
  rock(23, 23, 11, 17); // 매달린 배관(판 2 위 2칸 틈)
  rock(16, 17, 12, 13); // 발사대 팔(13)
  rock(1, 4, 17, 18); // 발사대 갑판(18) 왼쪽 조각
  rock(10, 30, 17, 18); // 발사대 갑판. 칸 5~9가 올라오는 구멍

  // ── 화면 2 (18~33) 노즐 밑과 첫 분사: 분사 판 소개. 실패해도 갑판(18)으로 돌아온다 ──
  rock(1, 13, 24, 57); // 발사탑(왼쪽 덩어리). 윗면(57)이 화면 4의 바닥
  rock(14, 17, 20, 57); // 로켓 동체 아랫부분. 밑면(20)이 노즐
  hot(14, 17, 18); // 노즐 밑 달궈진 갑판: 2칸 틈을 멈추지 않고 걸어 지난다(1.2초)
  boost(18, 19, 18); // 분사 판 1: 끝까지 가깝게 모아 10칸 위 선반으로(위는 받이 밑면이라 넘치면 머리를 박는다)
  boost(28, 30, 28); // 분사 선반(전체가 분사 판): 약하게 뛰어 4칸 위 팔로. 세게 뛰면 받이 턱 밑면에 박고 갑판으로 떨어진다
  rock(18, 21, 31, 32); // 로켓 팔 1(32)

  // ── 화면 3 (33~57) 로켓 오른쪽 벽: 벽 튕김 + 달궈진 판 + 꾸벅 패널 + 약한 분사(병목) ──
  rock(27, 30, 32, 35); // 받이(35): 낙하 통로의 바닥. 밑면은 분사 선반의 천장
  rock(23, 26, 36, 37); // 받이 턱(37). 팔 1에서 여기로, 받이에서도 여기로 올라온다
  hot(18, 18, 41); // 달궈진 팔(1칸): 로켓 벽에 붙어 길게 모아 벽에 튕겨 오른다
  nod(22, 23, 45); // 덜컹 패널
  boost(18, 18, 48); // 분사 팔(1칸). 1칸 발판까지 8칸 높이라 창이 8이다
  rock(26, 26, 55, 56); // 1칸 발판(56): 분사 팔에서 약하게(병목). 넘치면 낙하 통로로 받이까지
  rock(18, 19, 56, 57); // 승무원 통로 앞 턱(57)
  rock(14, 17, 59, 70); // 로켓 동체 윗부분. 57~59가 승무원 통로(2칸 틈)

  // ── 화면 4 (57~75) 발사탑 꼭대기: 꾸벅 패널 → 달궈진 판 2연속 → 로켓 머리 넘기(병목) ──
  down(14, 73, 4, { to: 70 }); // 로켓 머리: 오른쪽으로 쏟아지는 경사. 닿으면 통로 앞(57)이나 받이 선반(68)으로
  nod(2, 3, 61); // 덜컹 패널
  hot(7, 9, 64); // 달궈진 판 3
  rock(6, 10, 67, 69); // 철골 덩어리. 밑면은 판 3의 천장, 윗면(69)이 다음 발판
  hot(1, 2, 66); // 달궈진 판 4: 위 기둥 밑면(70) 때문에 세게 뛸 수 없다(시간 제한 + 세기 상한)
  rock(1, 3, 70, 95); // 발사탑 기둥(왼쪽 벽). 윗면(95)은 화면 6 바닥의 일부
  rock(10, 12, 73, 74); // 머리 옆 발판(74). 오른쪽으로 걸어 나가면 경사다
  rock(22, 24, 67, 68); // 받이 선반(68): 머리에서 미끄러지거나 화면 5에서 떨어졌을 때 일부를 받는다
  rock(22, 24, 74, 75); // 에어록 바닥(75): 3칸 틈으로 뛰어든다
  rock(22, 24, 78, 83); // 에어록 지붕. 윗면(83)은 화면 5의 발판
  rock(26, 27, 72, 100); // 낙하 통로의 왼쪽 벽

  // ── 화면 5 (75~95) 우주정거장: 전지판 능선 → 멀리뛰기(병목, 위는 달궈진 판 밑면) → 달궈진 판 걷기 → 좁은 모듈 ──
  rock(11, 12, 77, 80); // 능선(80)
  up(8, 77, 3); // 태양 전지판: 능선 왼쪽은 미끄럽다
  hot(13, 16, 88); // 달궈진 판 5: 오른쪽에 내려 모듈 밑을 걸어 왼쪽 끝에서 뛴다(0.9~1.2초)
  rock(14, 15, 90, 95); // 매달린 모듈(판 5 위 2칸 틈)
  rock(7, 8, 89, 90); // 작은 모듈(90). 왼쪽 기둥에 튕겨 위 바닥으로 나간다
  rock(4, 10, 84, 85); // 하부 갑판(85): 판 5와 작은 모듈에서 놓친 사람을 5칸 아래에서 받는다
  rock(7, 25, 94, 95); // 정거장 지붕 = 화면 6 바닥. 칸 4~6이 올라오는 구멍

  // ── 화면 6 (95~115) 소행성대: 숨 고르기. 어디서 떨어져도 정거장 지붕(95)이다 ──
  up(4, 99, 3); // 전지판 조각: 구멍의 뚜껑. 위에서 떨어지면 기둥 위로 미끄러진다
  rock(12, 13, 98, 99); // 소행성 1
  rock(19, 20, 101, 103); // 소행성 2(바람 골 안)
  nod(13, 14, 106); // 덜컹 패널
  rock(4, 4, 108, 109); // 소행성 3(1칸). 109보다 높이면 끝까지 누른 점프가 난간을 넘어 전지판으로 떨어진다
  rock(9, 12, 113, 115); // 관문 앞 쉼터(115). 설 수 있는 곳은 칸 7.6~10.5
  rock(12, 12, 115, 117); // 난간: 쉼터에서 전지판으로 걸어 나가지 못하게 막는다
  down(12, 117, 1); // 난간 머리는 경사(꼭대기 118). 오른쪽 면이 벽이 아니라서 분사 판에서 왼쪽으로 뛰어 튕겨 오는 꼼수가 없다
  down(13, 114, 15); // 큰 태양 전지판: 화면 6의 지붕이자 관문의 낙하 경로. 닿으면 낙하 통로로 쏟아진다
  wind(15, 25, 96, 108, 140); // 전지판 밑 바람 골(오른쪽으로 분다): 소행성 2를 오가는 두 점프가 밀린다

  // ── 화면 7 (115~130) 최종 관문: 난간 넘어 분사 판 → 약한 분사로 1칸 달궈진 판 → 2칸 문틈 → 구덩이 건너 턱 → 벽 튕김 → 쉼터 ──
  // 앞의 세 점프는 놓치면 큰 전지판을 타고 받이(35~37)까지 80칸 떨어진다. 문틈 뒤는 구덩이(115)가 받는다.
  // 전지판 위에 발판을 둘 때: 발판 밑면이 전지판에서 1.2칸보다 가까우면 미끄러지던 캐릭터가 끼인다(칸 c 에서 밑면 ≥ 130.7 - c).
  boost(15, 16, 117); // 분사 판(2칸): 쉼터에서 난간을 넘어 내린다. 끝까지 누르면 지나친다
  hot(19, 19, 120); // 달궈진 판(1칸): 분사 판 왼쪽 끝에서 아주 약하게(0.19~0.27초). 넘치면 받이까지
  rock(26, 27, 113, 122); // 문턱 기둥(122). 문틈으로 뛰어들어 여기 선다. 구덩이의 왼쪽 벽이기도 하다
  rock(26, 26, 124, 127); // 문 위 벽(문틈 높이 2칸)
  boost(28, 30, 115); // 구덩이 바닥(분사 판): 문턱보다 7칸 낮아 여기서는 문틈으로 도로 나갈 수 없다. 문턱이나 안쪽 턱으로 올라온다
  rock(30, 30, 123, 124); // 안쪽 턱(124, 1칸): 문턱에서 구덩이를 건너뛴다. 여기서 오른쪽 벽에 튕겨 받이 지붕으로
  rock(15, 26, 127, 129); // 받이 지붕(129): 쉼터 오른쪽으로 떨어진 사람을 받는다. 오른쪽 끝(칸 27~30) 아래가 구덩이다

  // ── 달(구간 6) 쉼터 ──
  rock(1, 14, top - 2, top);
}

