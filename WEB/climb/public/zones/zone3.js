// 구간 3 구름 위 성 (내 높이 0~136, 화면 7장). 높이는 "내 시작 바닥이 0"이라고 보고 쓴다.
// 시작 바닥은 아래 구간의 맨 위 쉼터(칸 1~14)다. 주제 장치는 낮은 천장: 세게 뛰면 머리를 박고 떨어진다.
// 큰 구조: 화면 사이마다 층 바닥이 있고 구멍 하나로만 올라간다. 병목은 그 구멍 위에서 뛰게 해서, 실패하면 아래 화면으로 떨어진다.
//   가운데 굴뚝(칸 12~13, 높이 73~112): 관문 첨탑에서 미끄러져 돌아오면 여기로 빠져 화면 4의 바닥(55)까지 떨어진다.
// 설계 메모: docs/research/zone3_design.md
export const top = 136;
export default function build({ rock, up, down, nod }) {
  // ── 화면 1 (0~19) 성문 앞: 천장을 가르친다. 어디서 떨어져도 앞마당이나 시작 바닥(9칸 이하) ──
  rock(15, 19, 4, 6); rock(20, 30, 2, 6); // 앞마당(6). 밑을 띄운 것은 아래 구간의 마지막 점프 길을 막지 않기 위해서다
  rock(7, 10, 4, 5); // 성문 상인방(5)
  rock(7, 13, 8, 14); // 문루 몸체: 밑면(8)이 상인방 위 천장. 세게 뛰면 박고 앞마당에 못 닿는다
  rock(1, 13, 14, 15); // 문루 마루(15)
  rock(26, 30, 10, 11); // 망루 턱(11)
  rock(26, 28, 14, 15); // 통로 첫 발판(15). 망루 턱에서 오른쪽 벽에 튕겨 올라선다
  rock(18, 20, 14, 15); // 통로 둘째 발판(15)
  rock(11, 30, 18, 19); // 통로 천장 1 (밑면 18)
  rock(11, 20, 17, 18); // 통로 천장 2 (밑면 17): 천장이 한 칸 낮아진다. 여기부터는 톡 점프만 지나간다

  // ── 화면 2 (19~37) 작은 첨탑: 지붕 타기와 처마 밑 벽 튕김을 가르친다. 떨어지면 바닥(19) ──
  rock(5, 7, 22, 23); // 디딤 1(23)
  rock(9, 11, 27, 28); // 디딤 2(28): 오른쪽 끝에서 뛰어 지붕 꼭대기를 넘는다
  up(14, 28, 4, { to: 23 }); down(18, 31, 4, { to: 23 }); // 첨탑 지붕(꼭대기 32). 넘으면 오른쪽 면을 타고 처마 밑 턱으로 날아간다. 못 넘으면 왼쪽으로 미끄러져 돌아온다. 밑(19~23)은 지나다니는 회랑
  rock(24, 27, 26, 27); // 처마 밑 턱(27)
  rock(24, 27, 30, 31); // 위 턱(31): 아래 턱 오른쪽 끝에서 뛰어 벽에 튕겨 돌아 올라선다
  rock(25, 30, 33, 35); // 위 턱의 천장 (밑면 33). 세게 뛰면 박고 일찍 떨어져 턱에 못 닿는다
  rock(1, 18, 35, 37); rock(25, 30, 35, 37); // 화면 3 바닥(37). 구멍은 칸 19~24

  // ── 화면 3 (37~55) 낮아지는 통로: 천장 밑에서 구덩이 두 번. 둘째 구덩이(병목)는 구멍 위라서 화면 2까지 떨어진다 ──
  rock(1, 2, 41, 42); // 디딤(42)
  rock(4, 7, 45, 46); // 통로 발판 1(46)
  rock(15, 18, 45, 46); // 통로 발판 2(46)
  rock(25, 26, 45, 46); // 통로 발판 3(46)
  rock(1, 22, 50, 55); // 천장 1 (밑면 50). 윗면(55)이 화면 4 바닥
  rock(23, 24, 49, 55); // 천장 2 (밑면 49): 구덩이 끝에서 한 칸 낮아진다. 높이 뜬 점프는 이 턱에 걸린다
  rock(29, 30, 49, 50); // 오른쪽 벽 턱(50): 여기서 왼쪽 위 화면 4 바닥으로

  // ── 화면 4 (55~73) 나선 계단 탑: 막다른 단에서 내려뛰어 처마 밑으로, 그 끝에서 벽에 튕겨 돌아 올라간다(병목) ──
  rock(7, 9, 59, 60); // 계단 1(60): 폭 3칸(사용자 요청으로 2차 수정 전 모양으로 되돌림)
  rock(16, 16, 65, 66); // 막다른 단(66): 폭 1칸. 넘치면 바닥으로 떨어진다. 여기서 오른쪽 아래 처마 밑으로 내려뛴다
  rock(13, 18, 69, 71); // 막다른 단 위 들보 (밑면 69)
  rock(24, 25, 63, 64); rock(26, 27, 63, 65); // 처마 밑 턱(64)과 한 칸 높은 디딤(65)
  rock(24, 27, 67, 68); // 처마(68): 디딤 오른쪽 끝에서 뛰어 오른쪽 벽에 튕겨 돌아 올라선다. 실패하면 화면 3의 오른쪽 벽 턱(50)이나 발판 3(46)
  rock(25, 30, 70, 71); // 처마 위 천장 (밑면 70)
  rock(1, 7, 71, 73); rock(14, 18, 71, 73); rock(24, 30, 71, 82); // 화면 5 바닥(73). 구멍은 칸 8~13(굴뚝)과 칸 19~23. 오른쪽 덩어리 윗면(82)이 첨탑 건너편 성벽

  // ── 화면 5 (73~94) 첨탑 타기(병목): 꼭대기를 딱 넘겨 오른쪽 지붕을 타고 건너편 성벽으로. 못 넘으면 굴뚝으로 빠져 화면 4 바닥까지 ──
  rock(2, 3, 78, 79); // 디딤(79): 벽에서 한 칸 뗐다
  rock(8, 10, 84, 85); // 발사대(85)
  up(13, 85, 4, { to: 77 }); down(17, 88, 2, { to: 77 }); down(19, 86, 1, { depth: 1 }); // 첨탑 지붕(꼭대기 89, 처마 86). 밑(73~77)은 회랑
  rock(29, 30, 87, 88); // 오른쪽 벽 턱(88)

  // ── 화면 6 (94~112) 성벽 위: 숨 고르기. 떨어져도 성벽 바닥(94) ──
  rock(1, 11, 92, 110); rock(1, 9, 110, 112); down(10, 111, 2); // 굴뚝 왼쪽 통짜 벽. 윗면(112, 칸 1~9)이 관문 왼쪽 바닥이고 오른쪽 끝 두 칸은 굴뚝으로 흘러내리는 경사. 밑면(92)은 화면 5 발사대 쪽 천장
  rock(14, 26, 92, 94); // 성벽 바닥(94). 굴뚝은 칸 12~13, 올라오는 구멍은 칸 27~30. 밑면(92)이 화면 5 첨탑의 천장
  rock(14, 14, 94, 110); // 굴뚝 오른쪽 벽
  rock(16, 16, 97, 98); // 성가퀴 1(98): 폭 1칸
  nod(25, 26, 99); // 구름 덩이(99): 2초 서면 꺼진다. 넘치면 성벽 바닥
  rock(20, 20, 104, 105); // 성가퀴 2(105): 폭 1칸
  rock(26, 28, 106, 107); // 관문 밑 턱(107): 왼쪽 끝에서 왼쪽 위 구멍으로

  // ── 화면 7 (112~136) 관문 첨탑: 화면 5와 같은 지붕 타기인데 지붕이 한 칸 짧다. 실패하면 굴뚝으로 화면 4 바닥까지(약 70칸) ──
  rock(14, 20, 110, 112); // 관문 회랑 바닥(112). 굴뚝 구멍은 칸 12~13, 올라오는 구멍은 칸 21~25
  rock(26, 30, 110, 120); // 건너편 성벽(120)
  rock(4, 5, 117, 118); // 디딤(118): 벽에서 뗐다
  rock(10, 12, 123, 124); // 발사대(124)
  rock(11, 11, 124, 125); // 발사대 위 턱: 오른쪽에 내려 왼쪽으로 걸어 붙으면 그 자리가 발사 자리다
  up(15, 124, 4, { to: 116 }); down(19, 127, 2, { to: 116 }); // 관문 첨탑(꼭대기 128, 처마 126)
  rock(29, 30, 123, 124); // 오른쪽 벽 턱(124)
  rock(22, 25, 128, 130); // 안뜰 낮은 단(130)
  rock(16, 21, 131, 134); rock(15, 15, 133, 134); // 쉼터 옆 받이(134): 쉼터에서 오른쪽으로 걸어 나가도 여기 선다. 밑면(131)은 관문 첨탑의 천장

  // ── 구간 4 쉼터 ──
  rock(1, 14, top - 2, top);
}

