// 디딤은 모두 시작 바닥(구간 5 쉼터, 칸 1~14) 위에 있고, 달 표면 밑면(8)이 디딤 2와 붙어 있어서 오른쪽으로 약하게 뛰어도 표면 밑으로 빠지지 않는다.
