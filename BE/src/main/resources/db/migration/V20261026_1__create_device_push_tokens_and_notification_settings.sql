CREATE TABLE device_push_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  BIGINT        NOT NULL,
    token      VARCHAR(1024) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL,
    updated_at TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_device_push_tokens_device_id UNIQUE (device_id),
    CONSTRAINT uk_device_push_tokens_token UNIQUE (token),
    CONSTRAINT ck_device_push_tokens_token CHECK (length(token) > 0),
    CONSTRAINT fk_device_push_tokens_device
        FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE TABLE device_notification_settings
(
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id                    BIGINT      NOT NULL,
    collection_claimable_enabled BOOLEAN     NOT NULL,
    rank_changed_enabled         BOOLEAN     NOT NULL,
    created_at                   TIMESTAMPTZ NOT NULL,
    updated_at                   TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_device_notification_settings_device_id UNIQUE (device_id),
    CONSTRAINT fk_device_notification_settings_device
        FOREIGN KEY (device_id) REFERENCES devices (id)
);
