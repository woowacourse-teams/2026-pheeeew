-- 자산 경로는 collection-cards/ 기준 상대 경로다. 환경별 S3/CDN 주소는 애플리케이션 설정에서 지정한다.
-- 발급에 사용한 자산은 수정·삭제하지 않고 새 card_version으로 추가한다.
CREATE TABLE collection_character_assets
(
    card_version VARCHAR(64) NOT NULL,
    state VARCHAR(20) NOT NULL,
    asset_number INTEGER NOT NULL,
    image_path VARCHAR(512) NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (card_version, state, asset_number),
    CONSTRAINT ck_collection_character_version CHECK (card_version ~ '^[a-zA-Z0-9_-]{1,64}$'),
    CONSTRAINT ck_collection_character_state CHECK (state IN ('FRUSTRATED', 'IRRITATED', 'EXHAUSTED', 'DISCOURAGED', 'ANGRY')),
    CONSTRAINT ck_collection_character_number CHECK (asset_number BETWEEN 1 AND 16),
    CONSTRAINT ck_collection_character_dimensions CHECK (width > 0 AND height > 0),
    CONSTRAINT ck_collection_character_path CHECK
        (image_path = card_version || '/characters/' || lower(state) || '/' || lpad(asset_number::text, 2, '0') || '.png'),
    CONSTRAINT uk_collection_character_path UNIQUE (image_path)
);

CREATE TABLE collection_stamp_assets
(
    card_version VARCHAR(64) NOT NULL,
    state VARCHAR(20) NOT NULL,
    asset_number INTEGER NOT NULL,
    round_image_path VARCHAR(512) NOT NULL,
    round_width INTEGER NOT NULL,
    round_height INTEGER NOT NULL,
    straight_image_path VARCHAR(512) NOT NULL,
    straight_width INTEGER NOT NULL,
    straight_height INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (card_version, state, asset_number),
    CONSTRAINT ck_collection_stamp_version CHECK (card_version ~ '^[a-zA-Z0-9_-]{1,64}$'),
    CONSTRAINT ck_collection_stamp_state CHECK (state IN ('FRUSTRATED', 'IRRITATED', 'EXHAUSTED', 'DISCOURAGED', 'ANGRY')),
    CONSTRAINT ck_collection_stamp_number CHECK (asset_number BETWEEN 1 AND 16),
    CONSTRAINT ck_collection_stamp_dimensions CHECK
        (round_width > 0 AND round_height > 0 AND straight_width > 0 AND straight_height > 0),
    CONSTRAINT ck_collection_stamp_round_path CHECK
        (round_image_path = card_version || '/stamps-round/' || lower(state) || '/' || lpad(asset_number::text, 2, '0') || '.png'),
    CONSTRAINT ck_collection_stamp_straight_path CHECK
        (straight_image_path = card_version || '/stamps-straight/' || lower(state) || '/' || lpad(asset_number::text, 2, '0') || '.png'),
    CONSTRAINT uk_collection_stamp_round_path UNIQUE (round_image_path),
    CONSTRAINT uk_collection_stamp_straight_path UNIQUE (straight_image_path)
);

