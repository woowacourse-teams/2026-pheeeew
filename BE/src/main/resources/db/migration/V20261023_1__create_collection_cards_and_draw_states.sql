CREATE TABLE collection_draw_states
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id              BIGINT      NOT NULL,
    state                  VARCHAR(20) NOT NULL,
    cycle                  BIGINT      NOT NULL,
    last_combination_index INTEGER,
    created_at             TIMESTAMPTZ NOT NULL,
    updated_at             TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_collection_draw_states_device_state UNIQUE (device_id, state),
    CONSTRAINT fk_collection_draw_states_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_collection_draw_states_state
        CHECK (state IN ('FRUSTRATED', 'IRRITATED', 'EXHAUSTED', 'DISCOURAGED', 'ANGRY')),
    CONSTRAINT ck_collection_draw_states_cycle CHECK (cycle > 0),
    CONSTRAINT ck_collection_draw_states_last_combination
        CHECK (last_combination_index BETWEEN 0 AND 255),
    CONSTRAINT ck_collection_draw_states_cycle_has_previous
        CHECK (cycle = 1 OR last_combination_index IS NOT NULL)
);

CREATE TABLE collection_cards
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         UUID        NOT NULL,
    device_id         BIGINT      NOT NULL,
    card_date         DATE        NOT NULL,
    state             VARCHAR(20) NOT NULL,
    cycle             BIGINT      NOT NULL,
    combination_index INTEGER     NOT NULL,
    card_version      VARCHAR(64) NOT NULL,
    character_number  INTEGER GENERATED ALWAYS AS (combination_index / 16 + 1) STORED,
    stamp_number      INTEGER GENERATED ALWAYS AS (combination_index % 16 + 1) STORED,
    claimed_at        TIMESTAMPTZ NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_collection_cards_public_id UNIQUE (public_id),
    CONSTRAINT uk_collection_cards_device_date_state UNIQUE (device_id, card_date, state),
    CONSTRAINT uk_collection_cards_device_state_cycle_combination
        UNIQUE (device_id, state, cycle, combination_index),
    CONSTRAINT fk_collection_cards_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT fk_collection_cards_character FOREIGN KEY (card_version, state, character_number)
        REFERENCES collection_character_assets (card_version, state, asset_number),
    CONSTRAINT fk_collection_cards_stamp FOREIGN KEY (card_version, state, stamp_number)
        REFERENCES collection_stamp_assets (card_version, state, asset_number),
    CONSTRAINT ck_collection_cards_state
        CHECK (state IN ('FRUSTRATED', 'IRRITATED', 'EXHAUSTED', 'DISCOURAGED', 'ANGRY')),
    CONSTRAINT ck_collection_cards_cycle CHECK (cycle > 0),
    CONSTRAINT ck_collection_cards_combination CHECK (combination_index BETWEEN 0 AND 255),
    CONSTRAINT ck_collection_cards_card_version CHECK (length(trim(card_version)) > 0)
);
