CREATE TABLE notification_collection_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(40) NOT NULL,
    device_id        BIGINT      NOT NULL,
    target_date      DATE        NOT NULL,
    status           VARCHAR(20) NOT NULL,
    discovered_at    TIMESTAMPTZ NOT NULL,
    available_at     TIMESTAMPTZ NOT NULL,
    expires_at       TIMESTAMPTZ NOT NULL,
    attempt_count    INTEGER     NOT NULL DEFAULT 0,
    claim_token      UUID,
    claim_expires_at TIMESTAMPTZ,
    result_code      VARCHAR(40),
    finished_at      TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_notification_collection_outbox_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_notification_collection_outbox_type
        CHECK (type IN ('COLLECTION_CLAIMABLE', 'COLLECTION_CLAIM_REMINDER')),
    CONSTRAINT ck_notification_collection_outbox_claim CHECK ((claim_token IS NULL) = (claim_expires_at IS NULL)),
    CONSTRAINT ck_notification_collection_outbox_attempt_count CHECK (attempt_count >= 0)
);

CREATE UNIQUE INDEX uk_notification_collection_outbox
    ON notification_collection_outbox (device_id, target_date, type);

CREATE INDEX ix_notification_collection_outbox_pending
    ON notification_collection_outbox (available_at) WHERE status = 'PENDING';

CREATE TABLE notification_rank_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id        BIGINT      NOT NULL,
    target_date      DATE        NOT NULL,
    round_at         TIMESTAMPTZ NOT NULL,
    previous_rank    INTEGER     NOT NULL,
    current_rank     INTEGER     NOT NULL,
    status           VARCHAR(20) NOT NULL,
    discovered_at    TIMESTAMPTZ NOT NULL,
    available_at     TIMESTAMPTZ NOT NULL,
    expires_at       TIMESTAMPTZ NOT NULL,
    attempt_count    INTEGER     NOT NULL DEFAULT 0,
    claim_token      UUID,
    claim_expires_at TIMESTAMPTZ,
    result_code      VARCHAR(40),
    finished_at      TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_notification_rank_outbox_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_notification_rank_outbox_claim CHECK ((claim_token IS NULL) = (claim_expires_at IS NULL)),
    CONSTRAINT ck_notification_rank_outbox_attempt_count CHECK (attempt_count >= 0)
);

CREATE UNIQUE INDEX uk_notification_rank_outbox
    ON notification_rank_outbox (device_id, round_at);

CREATE INDEX ix_notification_rank_outbox_pending
    ON notification_rank_outbox (available_at) WHERE status = 'PENDING';

CREATE TABLE notification_rank_rounds
(
    round_at    TIMESTAMPTZ PRIMARY KEY,
    target_date DATE        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE notification_rank_snapshots
(
    round_at  TIMESTAMPTZ NOT NULL,
    device_id BIGINT      NOT NULL,
    rank      INTEGER     NOT NULL,
    CONSTRAINT pk_notification_rank_snapshots PRIMARY KEY (round_at, device_id),
    CONSTRAINT fk_notification_rank_snapshots_round
        FOREIGN KEY (round_at) REFERENCES notification_rank_rounds (round_at) ON DELETE CASCADE,
    CONSTRAINT fk_notification_rank_snapshots_device FOREIGN KEY (device_id) REFERENCES devices (id)
);
