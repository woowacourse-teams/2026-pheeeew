CREATE TABLE collection_claimable_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id        BIGINT      NOT NULL,
    target_date      DATE        NOT NULL,
    status           VARCHAR(20) NOT NULL,
    discovered_at    TIMESTAMPTZ NOT NULL,
    available_at     TIMESTAMPTZ NOT NULL,
    expires_at       TIMESTAMPTZ NOT NULL,
    attempt_count    INTEGER     NOT NULL,
    claim_token      UUID,
    claim_expires_at TIMESTAMPTZ,
    result_code      VARCHAR(40),
    finished_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_collection_claimable_outbox_device FOREIGN KEY (device_id) REFERENCES devices (id)
);

CREATE UNIQUE INDEX uk_collection_claimable_outbox
    ON collection_claimable_outbox (device_id, target_date);

CREATE INDEX ix_collection_claimable_outbox_pending
    ON collection_claimable_outbox (available_at) WHERE status = 'PENDING';

