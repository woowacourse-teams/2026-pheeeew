CREATE TABLE notification_outbox
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(40) NOT NULL,
    device_id        BIGINT      NOT NULL,
    target_date      DATE        NOT NULL,
    round_at         TIMESTAMPTZ,
    previous_rank    INTEGER,
    current_rank     INTEGER,
    status           VARCHAR(20) NOT NULL,
    discovered_at    TIMESTAMPTZ NOT NULL,
    available_at     TIMESTAMPTZ NOT NULL,
    expires_at       TIMESTAMPTZ NOT NULL,
    attempt_count    INTEGER     NOT NULL DEFAULT 0,
    claim_token      UUID,
    claim_expires_at TIMESTAMPTZ,
    result_code      VARCHAR(40),
    finished_at      TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_notification_outbox_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_notification_outbox_type
        CHECK (type IN ('COLLECTION_CLAIMABLE', 'COLLECTION_CLAIM_REMINDER', 'RANK_DROPPED')),
    CONSTRAINT ck_notification_outbox_status CHECK (status IN ('PENDING', 'SENT', 'CANCELED', 'FAILED')),
    CONSTRAINT ck_notification_outbox_rank_fields CHECK (
        (type = 'RANK_DROPPED' AND round_at IS NOT NULL
            AND previous_rank BETWEEN 1 AND 5 AND current_rank > previous_rank)
        OR (type <> 'RANK_DROPPED' AND round_at IS NULL AND previous_rank IS NULL AND current_rank IS NULL)
    ),
    CONSTRAINT ck_notification_outbox_claim CHECK ((claim_token IS NULL) = (claim_expires_at IS NULL)),
    CONSTRAINT ck_notification_outbox_finished CHECK (
        (status = 'PENDING' AND finished_at IS NULL)
        OR (status <> 'PENDING' AND finished_at IS NOT NULL AND claim_token IS NULL)
    ),
    CONSTRAINT ck_notification_outbox_attempt_count CHECK (attempt_count >= 0)
);

CREATE UNIQUE INDEX uk_notification_outbox_collection
    ON notification_outbox (device_id, target_date, type) WHERE round_at IS NULL;

CREATE UNIQUE INDEX uk_notification_outbox_rank
    ON notification_outbox (device_id, target_date, round_at, type) WHERE round_at IS NOT NULL;

CREATE INDEX ix_notification_outbox_pending ON notification_outbox (available_at) WHERE status = 'PENDING';

CREATE TABLE notification_rank_rounds
(
    round_at    TIMESTAMPTZ PRIMARY KEY,
    target_date DATE        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE notification_rank_snapshots
(
    round_at  TIMESTAMPTZ NOT NULL,
    device_id BIGINT      NOT NULL,
    rank      INTEGER     NOT NULL,
    CONSTRAINT pk_notification_rank_snapshots PRIMARY KEY (round_at, device_id),
    CONSTRAINT fk_notification_rank_snapshots_round
        FOREIGN KEY (round_at) REFERENCES notification_rank_rounds (round_at) ON DELETE CASCADE,
    CONSTRAINT fk_notification_rank_snapshots_device FOREIGN KEY (device_id) REFERENCES devices (id),
    CONSTRAINT ck_notification_rank_snapshots_rank CHECK (rank BETWEEN 1 AND 5)
);
