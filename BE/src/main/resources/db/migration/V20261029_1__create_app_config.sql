CREATE TABLE app_config
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform                    VARCHAR(20)  NOT NULL,
    daily_press_ranking_enabled  BOOLEAN      NOT NULL DEFAULT TRUE,
    notice_message              TEXT         NOT NULL DEFAULT '',
    revision                    BIGINT       NOT NULL DEFAULT 1,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_app_config_platform UNIQUE (platform),
    CONSTRAINT ck_app_config_platform CHECK (platform IN ('ANDROID', 'IOS')),
    CONSTRAINT ck_app_config_revision CHECK (revision > 0),
    CONSTRAINT ck_app_config_notice_message_length CHECK (char_length(notice_message) <= 200)
);

INSERT INTO app_config (platform)
VALUES ('ANDROID'), ('IOS');
