#!/usr/bin/env python3
"""Audit a Release archive together with its Gradle graph and linker provenance."""
import argparse
import hashlib
from pathlib import Path
import plistlib
import re
import shlex
import struct

MARKERS = (b"DeveloperToolsInfo", b"DeveloperToolsScreen", b"DebugMainViewController", b"com.pheeeew.developertools")


def require(condition, message):
    """Reject invalid evidence even when Python optimization is enabled."""
    if not condition:
        raise ValueError(message)


def macho_uuid(path):
    """Read LC_UUID from the arm64 Mach-O executable, which survives stripping."""
    data = path.read_bytes()
    require(len(data) >= 32 and data[:4] == b"\xcf\xfa\xed\xfe", "Expected a 64-bit little-endian Mach-O executable")
    cursor = 32
    for _ in range(struct.unpack_from("<I", data, 16)[0]):
        require(cursor + 8 <= len(data), "Truncated Mach-O load command")
        command, size = struct.unpack_from("<II", data, cursor)
        require(size >= 8 and cursor + size <= len(data), "Invalid Mach-O load command")
        if command == 0x1B:
            require(size == 24, "Invalid LC_UUID command")
            return data[cursor + 8:cursor + 24]
        cursor += size
    raise ValueError("Missing Mach-O LC_UUID")


def option(tokens, name):
    """Extract a required, unambiguous command-line option from Xcode's log."""
    require(tokens.count(name) == 1, f"Missing or ambiguous build option: {name}")
    index = tokens.index(name) + 1
    require(index < len(tokens), f"Missing build option value: {name}")
    return tokens[index]


def verify_provenance(archive, log, link_map_path, executable, release_framework):
    """Match the archive, linker output/map and shared Release framework inputs."""
    commands = [shlex.split(line) for line in log.splitlines() if " -archivePath " in line and "xcodebuild " in line]
    require(len(commands) == 1, "Expected one xcodebuild archive invocation")
    require(Path(option(commands[0], "-archivePath")).resolve() == archive.resolve(), "Build log belongs to a different archive")
    require(option(commands[0], "-configuration") == "Release", "Archive invocation must use Release")

    link_map = link_map_path.read_bytes()
    header = link_map.splitlines()[0].decode("utf-8")
    require(header.startswith("# Path: "), "Missing link map output path")
    linked_executable = Path(header.removeprefix("# Path: "))
    link_commands = []
    for line in log.splitlines():
        if " -map " in line and "/clang " in line:
            tokens = [token for token in shlex.split(line) if token != "-Xlinker"]
            if Path(option(tokens, "-map")).resolve() == link_map_path.resolve():
                link_commands.append(tokens)
    require(len(link_commands) == 1, "Link map was not generated by this archive build")
    require(Path(option(link_commands[0], "-o")).resolve() == linked_executable.resolve(), "Link map output does not match the linker output")
    uuid_source = linked_executable
    if not uuid_source.is_file():
        # Xcode moves the installed app into the Archive; its generated dSYM
        # remains in DerivedData and carries the UUID of the same link output.
        dsym_commands = [
            shlex.split(line) for line in log.splitlines() if "/dsymutil " in line
        ]
        dsym_commands = [
            tokens for tokens in dsym_commands
            if len(tokens) > 1 and Path(tokens[1]).resolve() == linked_executable.resolve()
        ]
        require(len(dsym_commands) == 1, "Missing dSYM provenance for the linked executable")
        uuid_source = Path(option(dsym_commands[0], "-o")) / "Contents/Resources/DWARF" / executable.name
    require(macho_uuid(executable) == macho_uuid(uuid_source), "Archived executable does not match the linked executable UUID")

    inputs = {
        Path(match.group(1)).resolve()
        for line in link_map.decode("utf-8", errors="replace").splitlines()
        if (match := re.match(r"^\[\s*\d+\]\s+(.+?Shared\.framework/Shared)(?:\(|\[|$)", line))
    }
    require(len(inputs) == 1, "Expected one static Shared framework input")
    framework = inputs.pop()
    expected = release_framework.resolve()
    release_copies = expected.parents[4] / "xcode-frameworks" / "Release"
    require(framework == expected or framework.is_relative_to(release_copies), "Link map input is not the shared Release framework")
    require(hashlib.sha256(framework.read_bytes()).digest() == hashlib.sha256(expected.read_bytes()).digest(), "Linked framework differs from the shared Release artifact")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, required=True)
    parser.add_argument("--build-log", type=Path, required=True)
    parser.add_argument("--graph-log", type=Path, required=True)
    parser.add_argument("--link-map", type=Path, required=True)
    args = parser.parse_args()
    log = args.build_log.read_text()
    if not ("** ARCHIVE SUCCEEDED **" in log):
        raise ValueError("Archive did not succeed")
    if not (":shared:linkReleaseFrameworkIosArm64" in log):
        raise ValueError("Missing Release framework link evidence")
    if not (":developerTools:" not in log):
        raise ValueError("Developer tools task ran in the Release archive build")
    graph = args.graph_log.read_text()
    if not ("iosArm64.main developerTools=false" in graph):
        raise ValueError("Missing resolved Release dependency evidence")
    if not ("BUILD SUCCESSFUL" in graph):
        raise ValueError("Dependency graph verification failed")
    link_map = args.link_map.read_bytes()
    if not (b"Shared.framework/Shared" in link_map):
        raise ValueError("Missing static Shared framework in the link map")
    if not (b"developerTools" not in link_map):
        raise ValueError("Developer tools input in Release link map")
    apps = list((args.archive / "Products/Applications").glob("*.app"))
    if not (len(apps) == 1):
        raise ValueError("Expected exactly one archived app")
    app = apps[0]
    with (app / "Info.plist").open("rb") as file:
        info = plistlib.load(file)
    if not (info["DEVICE_BUILD_CONFIGURATION"] == "Release"):
        raise ValueError('Invalid Release build settings')
    if not (info["DEVICE_ENVIRONMENT"] == "prod"):
        raise ValueError('Invalid Release build settings')
    if not (info["API_BASE_URL"] == "https://api.pheeeew.com"):
        raise ValueError('Invalid Release build settings')
    executable = app / info["CFBundleExecutable"]
    release_framework = Path(__file__).resolve().parent.parent / "shared/build/bin/iosArm64/releaseFramework/Shared.framework/Shared"
    verify_provenance(args.archive, log, args.link_map, executable, release_framework)
    files = [path for path in app.rglob("*") if path.is_file()]
    hits = [str(path.relative_to(app)) for path in files if any(marker in path.read_bytes() for marker in MARKERS)]
    if not (not hits):
        raise ValueError(f"Developer tools code/resources found: {hits}")
    print(f"{app}: {len(files)} executable/framework/resource files inspected, developerTools=false")
    print(f"version={info['CFBundleShortVersionString']} build={info['CFBundleVersion']} configuration=Release env=prod")
    print("executable sha256=" + hashlib.sha256(executable.read_bytes()).hexdigest())
    print(f"{args.link_map}: static Shared input present, no developer tools input")
    print("Release Gradle graph and Xcode task provenance verified; symbol absence is only a supplementary check.")


if __name__ == "__main__":
    main()
