#!/usr/bin/env python3
"""Regression checks for optimized Python and iOS archive/linker provenance."""
import importlib.util
from pathlib import Path
import shlex
import struct
import tempfile
import unittest
import zipfile


def load_script(name):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


android = load_script("inspect-developer-tools-android")
ios = load_script("inspect-developer-tools-ios")


def executable(uuid):
    return struct.pack("<8I", 0xFEEDFACF, 0x0100000C, 0, 2, 1, 24, 0, 0) + struct.pack("<II", 0x1B, 24) + uuid


class InspectionTest(unittest.TestCase):
    """Exercise valid evidence and common evidence mix-ups without building apps."""

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.archive = self.root / "app.xcarchive"
        self.archived = self.archive / "Products/Applications/App.app/App"
        self.linked = self.root / "build/App.app/App"
        self.expected = self.root / "shared/build/bin/iosArm64/releaseFramework/Shared.framework/Shared"
        self.framework = self.root / "shared/build/xcode-frameworks/Release/iphoneos/Shared.framework/Shared"
        for path, contents in (
            (self.archived, executable(b"a" * 16)),
            (self.linked, executable(b"a" * 16)),
            (self.expected, b"release static library"),
            (self.framework, b"release static library"),
        ):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        self.link_map = self.root / "App-LinkMap.txt"
        self.write_map(self.framework)
        self.log = shlex.join(["/usr/bin/xcodebuild", "-archivePath", str(self.archive), "-configuration", "Release"])
        self.log += "\n" + shlex.join(["/usr/bin/clang", "-Xlinker", "-map", "-Xlinker", str(self.link_map), "-o", str(self.linked)])

    def write_map(self, framework):
        self.link_map.write_text(f"# Path: {self.linked}\n# Arch: arm64\n# Object files:\n[ 1] {framework}(Shared.framework.o)\n")

    def verify(self, **overrides):
        args = dict(archive=self.archive, log=self.log, link_map_path=self.link_map, executable=self.archived, release_framework=self.expected)
        args.update(overrides)
        ios.verify_provenance(**args)

    def test_same_archive_and_release_framework_pass(self):
        self.verify()

    def test_different_archive_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "different archive"):
            self.verify(archive=self.root / "other.xcarchive")

    def test_unrelated_link_map_with_same_contents_is_rejected(self):
        other = self.root / "other-LinkMap.txt"
        other.write_bytes(self.link_map.read_bytes())
        with self.assertRaisesRegex(ValueError, "not generated by this archive"):
            self.verify(link_map_path=other)

    def test_debug_framework_with_release_bytes_is_rejected(self):
        debug = Path(str(self.framework).replace("/Release/", "/Debug/"))
        debug.parent.mkdir(parents=True)
        debug.write_bytes(self.expected.read_bytes())
        self.write_map(debug)
        with self.assertRaisesRegex(ValueError, "not the shared Release framework"):
            self.verify()

    def test_different_framework_contents_are_rejected(self):
        self.framework.write_bytes(b"unrelated static library")
        with self.assertRaisesRegex(ValueError, "differs from the shared Release artifact"):
            self.verify()

    def test_different_executable_uuid_is_rejected(self):
        self.archived.write_bytes(executable(b"b" * 16))
        with self.assertRaisesRegex(ValueError, "executable UUID"):
            self.verify()

    def test_moved_archive_uses_dsym_from_same_link_output(self):
        dsym = self.root / "build/App.app.dSYM"
        dwarf = dsym / "Contents/Resources/DWARF/App"
        dwarf.parent.mkdir(parents=True)
        dwarf.write_bytes(self.linked.read_bytes())
        self.linked.unlink()
        log = self.log + "\n" + shlex.join(["/usr/bin/dsymutil", str(self.linked), "-o", str(dsym)])
        self.verify(log=log)
        dwarf.write_bytes(executable(b"b" * 16))
        with self.assertRaisesRegex(ValueError, "executable UUID"):
            self.verify(log=log)

    def test_invalid_android_archive_is_rejected(self):
        path = self.root / "empty.apk"
        with zipfile.ZipFile(path, "w"):
            pass
        with self.assertRaisesRegex(ValueError, "Not an APK/AAB"):
            android.inspect(path, False)

    def test_android_release_containing_tools_is_rejected(self):
        path = self.root / "leaked.apk"
        with zipfile.ZipFile(path, "w") as archive:
            archive.writestr("classes.dex", "DeveloperToolsInfo")
            archive.writestr("AndroidManifest.xml", "manifest")
        with self.assertRaisesRegex(ValueError, "Unexpected developer tools"):
            android.inspect(path, False)


if __name__ == "__main__":
    unittest.main()
